    private void buttonpesqActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonpesqActionPerformed
    DefaultTableModel dm = (DefaultTableModel)tbdados.getModel();
while(dm.getRowCount() > 0)
{
    dm.removeRow(0);
}

        
        DefaultTableModel tab = (DefaultTableModel) tbdados.getModel();
us= new corrida();
ResultSet rs= null;
us.setNome(String.valueOf(txtpesq.getText()));
rs = us.PesquisarTodos();
try{
while (rs.next()){
tab.addRow(new Object[]{rs.getString("tb01_nome"), rs.getDouble("tb01_peso"), rs.getDouble("tb01_altura"), rs.getString("tb01_sexo"), rs.getString("tb01_email"), rs.getInt("tb01_inscricao")});
}
tbdados.setModel(tab);
}catch (SQLException ex){
    System.out.println("Erro:" +ex);
    }
    }//GEN-LAST:event_buttonpesqActionPerformed

