    private void tbdadosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbdadosMouseClicked
    try {     
            Conexao objetoBD = new Conexao();
        String sql = "SELECT * FROM tb01_corrida WHERE tb01_nome = '" + txtpesq.getText() + "'";
        objetoBD.Conectar();
       
        ResultSet rs = statement.executeQuery(sql);
        
        if (!rs.next())
        {
           JOptionPane.showMessageDialog(null, "Consulta Invalida");        
           return;
        }
        else
            {
            Image img = Toolkit.getDefaultToolkit().createImage(rs.getBytes("tb01_imagem"));
            ImageIcon foto = new ImageIcon(new ImageIcon(img).getImage().getScaledInstance(93, 126, Image.SCALE_DEFAULT));
            imgcima.setIcon(foto); 
            }
        
        objetoBD.desconectar();
        statement.close(); 
        }
               
        catch (Exception e)
        {
           System.out.println(e.getMessage());
        }     

    
    }//GEN-LAST:event_tbdadosMouseClicked

