    private void formInternalFrameOpened(javax.swing.event.InternalFrameEvent evt) {//GEN-FIRST:event_formInternalFrameOpened
DefaultTableModel tab = (DefaultTableModel) tblDados.getModel();
us= new Aluno();
ResultSet rs=null;
rs = us.PesquisarTodos();
try{
while (rs.next()){
tab.addRow(new Object[]{rs.getString("tb03_rm"), rs.getString("tb03_nome"), rs.getString("tb03_endereço"), rs.getString("tb03_telefone"), rs.getString("tb03_cpf")});
}
tblDados.setModel(tab);
}catch (SQLException ex){
    System.out.println("Erro:" +ex);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_formInternalFrameOpened

