    private void btnPesquisaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisaActionPerformed
        us= new Aluno();
        ResultSet rs= null;
        us.setRm(Integer.parseInt(txtRm.getText()));
        rs = us.PesquisarId();

        try {
            if(rs.next()){
                txtNome.setText(rs.getString("tb03_nome"));
                txtCpf.setText(rs.getString("tb03_cpf"));
                txtEnd.setText(rs.getString("tb03_endereço"));
                txtTel.setText(rs.getString("tb03_telefone"));

            }else{
                JOptionPane.showMessageDialog(null, "Erro ao cadastrar");

            }

            // TODO add your handling code here:
        } catch (SQLException ex) {
            Logger.getLogger(telaAluno.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnPesquisaActionPerformed

