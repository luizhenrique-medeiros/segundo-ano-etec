    private void formInternalFrameOpened(javax.swing.event.InternalFrameEvent evt) {//GEN-FIRST:event_formInternalFrameOpened
        Turma t = new Turma("","");
        ResultSet ka = t.carregar3();
        combTurma.addItem(new Turma("", "Selecione a turma"));
        try {
            while(ka.next()){
                combTurma.addItem(new Turma(ka.getString("tb02_cod_turma"),
                                            ka.getString("tb02_nome")));
            }
            ka.close();
        } catch (SQLException ex) {
            System.out.println("Erro: "+ex);
        }
        Aluno a = new Aluno(0,"");
        ResultSet rs = a.carregar2();
        combRM.addItem(new Aluno(0, "Selecione o rm"));
        try {
            while(rs.next()){
               combRM.addItem(new Aluno(rs.getInt("tb03_rm"),
               rs.getString("tb03_nome")));
                                            
            }
            rs.close();
        } catch (SQLException ex) {
            System.out.println("Erro: "+ex);
        }
        
        DefaultTableModel tab = (DefaultTableModel) tblDados.getModel();
        us= new Matricula();
        rs=null;
        rs = us.PesquisarTodos();
        try{
        while (rs.next()){
        tab.addRow(new Object[]{rs.getString("tb04_num"), rs.getString("tb04_cod_turma"), rs.getString("tb04_rm"), rs.getString("tb04_situação"), rs.getString("tb04_ano_letivo")});
        }
        tblDados.setModel(tab);
        }catch (SQLException ex){
        System.out.println("Erro:" +ex);
    } 
    }//GEN-LAST:event_formInternalFrameOpened

