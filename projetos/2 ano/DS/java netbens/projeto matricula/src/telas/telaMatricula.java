    private void btnPesquisaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisaActionPerformed
        us= new Matricula();
        ResultSet rs= null;
        us.setNmat(txtnmatricula.getText());
        rs = us.PesquisarId();
        
        try {
            if(rs.next()){
                txtanolet.setText(rs.getString("tb04_ano_letivo"));
                txtsituacao.setText(rs.getString("tb04_situação"));
                combTurma.setSelectedItem(rs.getString("tb04_cod_turma"));
                combRM.setSelectedItem(rs.getString("tb04_rm"));

            }else{
                JOptionPane.showMessageDialog(null, "Erro ao cadastrar");

            }

            // TODO add your handling code here:
        } catch (SQLException ex) {
            Logger.getLogger(telasUsuario.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnPesquisaActionPerformed

